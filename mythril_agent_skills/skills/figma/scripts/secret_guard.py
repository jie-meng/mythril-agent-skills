#!/usr/bin/env python3
"""Keep credential values out of everything a skill script prints.

Canonical source: mythril_agent_skills/shared/secrets/secret_guard.py.
Bundled copies under skills/<skill>/scripts/ are generated by
scripts/sync-shared-assets.py — never edit a bundled copy by hand.

Two layers of protection:

1. ``install(...)`` wraps ``sys.stdout`` / ``sys.stderr`` so that every
   write — normal prints, error messages, and uncaught-exception
   tracebacks — has credential values replaced by ``[REDACTED]``. It is
   called from each script's token getter, so it is active whenever a
   credential has been read, including when an agent imports the script
   and calls its functions directly.
2. ``guard_args(...)`` lets request functions refuse a call where a
   credential ended up in a non-credential argument (e.g. arguments passed
   in the wrong order), before the value can reach a URL or an error
   message. The refusal message never contains the value itself.
"""

from __future__ import annotations

import base64
import os
import sys
from urllib.parse import quote

REDACTED = "[REDACTED]"
MIN_SECRET_LENGTH = 8

_secrets: set[str] = set()


def secret_variants(value: str) -> set[str]:
    """Return the forms in which a secret may appear in printed text."""
    value = value.strip()
    if len(value) < MIN_SECRET_LENGTH:
        return set()
    return {value, quote(value, safe=""), quote(value)}


def basic_auth_variants(user: str, secret: str) -> set[str]:
    """Return the base64 forms of a ``user:secret`` Basic auth credential."""
    user, secret = user.strip(), secret.strip()
    if not user or len(secret) < MIN_SECRET_LENGTH:
        return set()
    encoded = base64.b64encode(f"{user}:{secret}".encode()).decode()
    return {encoded, encoded.rstrip("=")}


def redact_text(text: str, secrets: set[str] | frozenset[str]) -> str:
    """Replace every occurrence of each secret in ``text`` with REDACTED."""
    for secret in sorted(secrets, key=len, reverse=True):
        if secret and secret in text:
            text = text.replace(secret, REDACTED)
    return text


def find_leaks(named: dict[str, object], secrets: set[str] | frozenset[str]) -> list[str]:
    """Return the names of arguments whose string value contains a secret."""
    leaked = []
    for name, value in named.items():
        if isinstance(value, str) and any(s and s in value for s in secrets):
            leaked.append(name)
    return leaked


class _RedactingStream:
    """Text stream wrapper that redacts registered secrets on every write."""

    def __init__(self, stream) -> None:
        self._stream = stream

    def write(self, text: str) -> int:
        self._stream.write(redact_text(text, _secrets) if _secrets else text)
        return len(text)

    def writelines(self, lines) -> None:
        for line in lines:
            self.write(line)

    def __getattr__(self, name: str):
        return getattr(self._stream, name)


def register(*values: str) -> None:
    """Register literal secret values (and their encoded forms) for redaction."""
    for value in values:
        if value:
            _secrets.update(secret_variants(value))


def install(
    secret_envs: tuple[str, ...] | list[str],
    basic_auth_user_envs: tuple[str, ...] | list[str] = (),
) -> None:
    """Redact the given environment secrets from stdout/stderr from now on.

    ``basic_auth_user_envs`` names the username/email variables combined
    with each secret in an HTTP Basic auth header, so the base64 form of
    that header is redacted too. Safe to call more than once.
    """
    for name in secret_envs:
        secret = os.environ.get(name, "")
        register(secret)
        for user_env in basic_auth_user_envs:
            _secrets.update(basic_auth_variants(os.environ.get(user_env, ""), secret))
    for attr in ("stdout", "stderr"):
        stream = getattr(sys, attr)
        if stream is not None and not isinstance(stream, _RedactingStream):
            setattr(sys, attr, _RedactingStream(stream))


def guard_args(**named: object) -> None:
    """Refuse a call when a credential sits in a non-credential argument.

    Pass every argument that must NOT hold a credential (method, path,
    base_url, ...). Raises ValueError naming the argument, never its value.
    """
    leaked = find_leaks(named, frozenset(_secrets))
    if leaked:
        raise ValueError(
            "refusing request: a credential value was passed as argument(s) "
            f"{', '.join(leaked)} — check the argument order. Use the CLI "
            "subcommands instead of calling internal functions."
        )
